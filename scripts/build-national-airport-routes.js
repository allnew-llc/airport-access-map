import { mkdir, rename, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { NATIONAL_AIRPORT_CATALOG } from "../src/national-airport-catalog.js";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, "..");
const outputPath = path.join(projectRoot, "src", "national-airport-routes.js");
const temporaryPath = `${outputPath}.tmp`;

async function fetchRoute(item) {
  const [fromLongitude, fromLatitude] = item.airport;
  const [toLongitude, toLatitude] = item.gateway.coordinate;
  const endpoint = new URL(`https://router.project-osrm.org/route/v1/driving/${fromLongitude},${fromLatitude};${toLongitude},${toLatitude}`);
  endpoint.searchParams.set("overview", "simplified");
  endpoint.searchParams.set("geometries", "geojson");
  endpoint.searchParams.set("steps", "false");

  const response = await fetch(endpoint, {
    headers: { "user-agent": "AIRPORT-ACCESS-NOW-OSS-route-builder/1.0" },
    signal: AbortSignal.timeout(30_000)
  });
  if (!response.ok) throw new Error(`${item.code}: OSRM HTTP ${response.status}`);
  const payload = await response.json();
  const coordinates = payload.routes?.[0]?.geometry?.coordinates;
  if (!Array.isArray(coordinates) || coordinates.length < 2) throw new Error(`${item.code}: no routable geometry`);
  return coordinates;
}

const routes = {};
for (const item of NATIONAL_AIRPORT_CATALOG) {
  routes[item.id] = await fetchRoute(item);
  process.stdout.write(`${item.code} ${routes[item.id].length} points\n`);
}

const source = `// Generated by scripts/build-national-airport-routes.js.\n`
  + `// Geometry: OpenStreetMap contributors via the public OSRM demo server; ODbL 1.0.\n`
  + `export const NATIONAL_AIRPORT_ROUTES = Object.freeze(${JSON.stringify(routes, null, 2)});\n`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(temporaryPath, source, "utf8");
await rename(temporaryPath, outputPath);
process.stdout.write(`Wrote ${outputPath}\n`);
