export const messages = Object.freeze(Object.fromEntries(
  SUPPORTED_LOCALES.map((locale) => [locale, Object.freeze({
    ...baseMessages[locale],
    ...travelerMessages[locale]
  })])
));

export function normalizeLocale(value) {
  if (typeof value !== "string") return DEFAULT_LOCALE;
  const normalized = value.replace("_", "-").toLowerCase();
  if (normalized === "zh-tw" || normalized === "zh-hk" || normalized.startsWith("zh-hant")) return "zh-TW";
  if (normalized === "zh-cn" || normalized === "zh-sg" || normalized.startsWith("zh-hans") || normalized === "zh") return "zh-CN";
  if (normalized.startsWith("en")) return "en";
  if (normalized.startsWith("ko")) return "ko";
  if (normalized.startsWith("ja")) return "ja";
  return DEFAULT_LOCALE;
}

export function detectLocale({ storedLocale, browserLanguages = [] } = {}) {
  if (SUPPORTED_LOCALES.includes(storedLocale)) return storedLocale;
  for (const candidate of browserLanguages) {
    const locale = normalizeLocale(candidate);
    if (locale !== DEFAULT_LOCALE || String(candidate).toLowerCase().startsWith("ja")) return locale;
  }
  return DEFAULT_LOCALE;
}

export function initialLocale() {
  let storedLocale;
  try {
    storedLocale = globalThis.localStorage?.getItem(STORAGE_KEY) ?? undefined;
  } catch {
    storedLocale = undefined;
  }
  return detectLocale({ storedLocale, browserLanguages: globalThis.navigator?.languages ?? [] });
}

function interpolate(template, values) {
  return template.replace(/\{([^}]+)\}/g, (_, key) => String(values[key] ?? `{${key}}`));
}

export function createI18n(locale = initialLocale()) {
  let activeLocale = normalizeLocale(locale);
  return {
    get locale() { return activeLocale; },
    setLocale(nextLocale) {
      activeLocale = normalizeLocale(nextLocale);
      try { globalThis.localStorage?.setItem(STORAGE_KEY, activeLocale); } catch { /* storage is optional */ }
      return activeLocale;
    },
    t(key, values = {}) {
      const template = messages[activeLocale]?.[key] ?? messages[DEFAULT_LOCALE]?.[key] ?? key;
      return interpolate(template, values);
    },
    formatDate(value) {
      return new Intl.DateTimeFormat(activeLocale, {
        month: "2-digit",
        day: "2-digit",
        hour: "2-digit",
        minute: "2-digit",
        hour12: false,
        timeZone: "Asia/Tokyo"
      }).format(new Date(value));
    },
    formatSampleDate(value) {
      return new Intl.DateTimeFormat(activeLocale, {
        month: "long",
        day: "numeric",
        hour: "2-digit",
        minute: "2-digit",
        hour12: false,
        timeZone: "Asia/Tokyo"
      }).format(new Date(value));
    }
  };
}

export function applyDocumentTranslations(i18n) {
  document.documentElement.lang = i18n.locale;
  document.title = i18n.t("documentTitle");
  for (const element of document.querySelectorAll("[data-i18n]")) {
    element.textContent = i18n.t(element.dataset.i18n);
  }
  for (const element of document.querySelectorAll("[data-i18n-aria-label]")) {
    element.setAttribute("aria-label", i18n.t(element.dataset.i18nAriaLabel));
  }
  for (const element of document.querySelectorAll("[data-i18n-content]")) {
    element.setAttribute("content", i18n.t(element.dataset.i18nContent));
  }
  for (const element of document.querySelectorAll("[data-i18n-placeholder]")) {
    element.setAttribute("placeholder", i18n.t(element.dataset.i18nPlaceholder));
  }
}

export function localizedProperty(properties, field, locale) {
  if (locale === DEFAULT_LOCALE) return properties[field];
  return properties.translations?.[locale]?.[field] ?? properties[field];
}

export function usesJapaneseFallback(properties, locale) {
  if (properties.content_language === locale) return false;
  return locale !== DEFAULT_LOCALE && !properties.translations?.[locale]?.title;
}
