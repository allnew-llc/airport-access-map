const STATUS_RANK = Object.freeze({ unknown: -1, normal: 0, warning: 1, suspended: 2 });
const USER_FACING_TRANSPORT_STATUSES = new Set(["normal", "warning", "suspended"]);

export function userFacingTransportStatus(status) {
  return USER_FACING_TRANSPORT_STATUSES.has(status) ? status : null;
}

export function worstStatus(features = [], category) {
  if (!category) return "unknown";
  const categoryFeatures = features.filter((feature) => feature?.properties?.category === category);
  const nonDecisionScopes = new Set(["source_reachability_only", "network_reference_only"]);
  const verifiedFeatures = categoryFeatures.filter((feature) => !nonDecisionScopes.has(feature.properties.source_scope));
  const verifiedWorst = verifiedFeatures
    .reduce((worst, feature) => STATUS_RANK[feature.properties.status] > STATUS_RANK[worst] ? feature.properties.status : worst, "unknown");
  if (["warning", "suspended"].includes(verifiedWorst)) return verifiedWorst;
  if (categoryFeatures.some((feature) => nonDecisionScopes.has(feature.properties.source_scope))) return "unknown";
  return verifiedWorst;
}

export function routeStatusKey(status) {
  const visibleStatus = userFacingTransportStatus(status);
  if (!visibleStatus) return null;
  return {
    suspended: "routeStatusSuspended",
    warning: "routeStatusWarning",
    normal: "routeStatusNormal"
  }[visibleStatus];
}

